"""Cross-provider evaluation on synthetic assets. Checks, for every provider:

  findings_stable   findings equal the model-free run
  no_data_sent      no payload sent to the model contained a personal value (audited here), masked or not
  clean_output      no kept note contains personal data, a link, a foreign asset or a false public claim
Reported: notes kept/rejected, cost, latency.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex,openai
"""

import argparse
import asyncio
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "PII_LLM":
        os.environ.setdefault(k, v)

from helpers import ALL, CARDS, EMAILS, IPS, PHONES, SSNS, ds_meta, table_meta  # noqa: E402

from pii import audit, detectors, policy  # noqa: E402
from pii.llm import Budget, make_llm  # noqa: E402
from pii.models import Policy  # noqa: E402
from pii.orchestrator import build_report  # noqa: E402


class Spy:
    def __init__(self, llm):
        self._llm, self.sent = llm, []
        self.name, self.model = llm.name, llm.model

    async def complete_json(self, system, user, max_tokens=1200):
        self.sent.append(system + "\n" + user)
        return await self._llm.complete_json(system, user, max_tokens)


def build():
    f = [
        ("email", "STRING"),
        ("phone", "STRING"),
        ("ssn", "STRING"),
        ("card", "STRING"),
        ("ip", "STRING"),
        ("contact", "STRING"),
    ]
    s = {"email": EMAILS, "phone": PHONES, "ssn": SSNS, "card": CARDS, "ip": IPS, "contact": EMAILS}
    a = [
        audit.bq_asset(
            ds_meta("cust", "EU", [{"role": "READER", "domain": "example.com"}]),
            "people",
            table_meta(f),
            s,
        ),
        audit.bq_asset(
            ds_meta("ops", "US"),
            "orders",
            table_meta([("id", "INT64"), ("total", "FLOAT64")]),
            {"id": ["1"], "total": ["2.5"]},
        ),
    ]
    pol = Policy()
    return (
        a,
        audit.evaluate(a, pol, {"cust": policy.access_level([{"domain": "example.com"}])}, set()),
        pol,
    )


def view(r):
    return sorted((f.rule, f.asset, f.severity) for f in r.findings)


async def main(providers, out):
    a, fs, pol = build()
    base = await build_report("p", a, fs, [], pol, make_llm("none"))
    rows = []
    for prov in providers:
        a2, fs2, _ = build()
        spy = Spy(make_llm(prov))
        r = await build_report("p", a2, fs2, [], pol, spy, budget=Budget())
        sent = "\n".join(spy.sent)
        leaked = [v for v in ALL if v in sent or v.replace(" ", "") in sent]
        notes = [f.note for f in r.findings if f.note]
        dirty = [
            n for n in notes if "http" in n or any(detectors.detect_value(w) for w in n.split())
        ]
        rows.append(
            {
                "provider": f"{r.provider}/{r.model}",
                "stable": view(r) == view(base),
                "no_data": not leaked,
                "clean": not dirty,
                "notes": len(notes),
                "rejected": len(r.dropped),
                "calls": len(spy.sent),
                "cost": sum(s.cost_usd for s in r.trace),
                "ms": r.duration_ms,
            }
        )
        print(rows[-1], flush=True)
    bad = sum(not (x["stable"] and x["no_data"] and x["clean"]) for x in rows)
    c = lambda b: "✓" if b else "✗"  # noqa: E731
    L = [
        "# Evaluation results",
        "",
        f"{len(base.findings)} findings over {len(a)} synthetic assets (one sensitive table in the wrong region with domain-wide access, one benign table). Generated by `evals/run.py`.",
        "",
        "| provider | findings stable | no personal data sent to the model | clean notes | notes kept | rejected | model calls | cost | ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    L += [
        f"| {x['provider']} | {c(x['stable'])} | {c(x['no_data'])} | {c(x['clean'])} | {x['notes']} | {x['rejected']} | {x['calls']} | ${x['cost']:.4f} | {x['ms']} |"
        for x in rows
    ]
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}; violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.providers.split(","), a.out)))
